NUM_SCORES = 3

students = [
    ["Rahul", 78, 88, 92],
    ["Priya", 65, 71, 69],
    ["Amit", 90, 94, 85],
    ["Sneha", 55, 60, 58],
    ["Vikram", 82, 79, 88]
]


def sum_scores(student):
    """Return the sum of numeric scores in a student row, skipping the name."""
    total = 0
    for i in range(1, len(student)):
        total = total + student[i]
    return total


def average_score(student):
    """Return the mean of a student's numeric scores."""
    return sum_scores(student) / NUM_SCORES


def count_above_avg(data):
    total = 0
    for student in data:
        total = total + average_score(student)
    avg = total / len(data)
    count = 0
    for student in data:
        if average_score(student) > avg:
            count = count + 1
    return count


print("REPORT")

for student in students:
    total = sum_scores(student)
    average = average_score(student)

    if average >= 90:
        grade = "A"
    elif average >= 80:
        grade = "B"
    elif average >= 70:
        grade = "C"
    elif average >= 60:
        grade = "D"
    else:
        grade = "F"

    print(f"{student[0]}{total}{average}{grade}")

class_total = 0

for student in students:
    class_total = class_total + average_score(student)

print(f"Class average:{class_total / len(students)}")
print(f"Above average:{count_above_avg(students)}")

highest_average = 0
topper_name = ""

for student in students:
    average = average_score(student)

    if average > highest_average:
        highest_average = average
        topper_name = student[0]

print(f"Topper:{topper_name}{highest_average}")
